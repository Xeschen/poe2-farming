import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { gunzipSync } from 'node:zlib';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
const root = process.env.APP_URL || 'http://127.0.0.1:4173/';
const key = 'poe2-farming.personal.v1', errors = [];
try {
  for (const mobile of [false, true]) {
    const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, isMobile: mobile, hasTouch: mobile });
    const page = await context.newPage(); page.setDefaultTimeout(10000); page.on('pageerror', e => errors.push(e.message));
    const raw = () => page.evaluate(k => localStorage.getItem(k), key);
    const save = () => page.locator('.editor-save-actions [data-action="finish"]').click();
    const cancel = () => page.locator('.editor-save-actions [data-action="cancel-edit"]').click();
    await page.goto(new URL('?view=library', root).href);
    await page.getByRole('button', { name: '새 파밍법' }).click();
    await page.getByLabel('파밍법 이름 (필수)').fill('취소할 초안');
    assert.equal(await raw(), null); await cancel(); assert.equal(await raw(), null);
    assert.equal(await page.locator('#editor').count(), 0);
    await page.getByRole('button', { name: '새 파밍법' }).click();
    await page.getByLabel('파밍법 이름 (필수)').fill('저장할 세팅');
    const tier = page.getByLabel('경로석 등급', { exact: true }), affixes = page.getByLabel('속성 수', { exact: true });
    assert.equal(await tier.evaluate(el => el.tagName), 'SELECT');
    assert.deepEqual(await tier.locator('option').evaluateAll(els => els.map(el => el.value)), ['', ...Array.from({ length: 16 }, (_, i) => String(i + 1))]);
    assert.deepEqual(await affixes.locator('option').evaluateAll(els => els.map(el => el.value)), ['', ...Array.from({ length: 9 }, (_, i) => String(i))]);
    await tier.selectOption('16'); await affixes.selectOption('8');
    await page.getByLabel('타락 여부', { exact: true }).selectOption('false');
    const tops = await page.locator('.waystone-basics select').evaluateAll(els => els.map(e => e.getBoundingClientRect().top));
    assert.ok(Math.max(...tops) - Math.min(...tops) < 2, 'all three controls share a row');
    const ranges = page.locator('.waystone-properties');
    assert.equal(await ranges.getAttribute('open'), null);
    await ranges.locator('summary').click();
    assert.equal(await ranges.locator('.property-range').count(), 8);
    const boxes = await ranges.locator('.property-range').evaluateAll(els => els.slice(0, 3).map(e => ({ x: e.getBoundingClientRect().x, y: e.getBoundingClientRect().y })));
    assert.ok(Math.abs(boxes[0].y - boxes[1].y) < 2 && boxes[1].x > boxes[0].x && boxes[2].y > boxes[0].y);
    assert.ok(await page.evaluate(() => document.querySelector('.waystone-properties').compareDocumentPosition(document.querySelector('.waystone-options')) & Node.DOCUMENT_POSITION_FOLLOWING));
    await page.getByLabel('아이템 희귀도 최소', { exact: true }).fill('30');
    await page.getByLabel('몬스터 희귀도 최소', { exact: true }).fill('40');
    await page.locator('[data-op="add-tablet"]').click();
    assert.equal(await ranges.getAttribute('open'), '', 'expansion survives row changes');
    await page.getByRole('navigation', { name: '세팅 편집 목차' }).getByRole('link', { name: '경로석', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `test-results/editor-save-${mobile ? 'mobile' : 'desktop'}.png` });
    await ranges.locator('summary').click(); assert.equal(await ranges.getAttribute('open'), null);
    assert.equal(await raw(), null);
    await save(); const saved = await raw();
    assert.ok(saved); assert.equal(JSON.parse(saved).records.length, 1);
    assert.equal(JSON.parse(saved).records[0].method.waystone.properties.itemRarity.min, 30);
    await page.getByRole('button', { name: '세팅 편집' }).click();
    await page.getByLabel('파밍법 이름 (필수)').fill('취소할 변경');
    await tier.selectOption('1'); await page.getByLabel('나의 메모', { exact: true }).fill('discard');
    assert.equal(await raw(), saved);
    await page.locator('.top-nav [data-page="home"]').click(); assert.equal(await page.locator('#editor').count(), 1);
    await cancel(); assert.equal(await raw(), saved); assert.match(await page.locator('#content').innerText(), /저장할 세팅/);
    await page.getByRole('button', { name: '세팅 편집' }).click();
    await page.getByLabel('파밍법 이름 (필수)').fill('');
    await save(); assert.equal(await page.locator('#editor').count(), 1); assert.equal(await raw(), saved);
    await cancel(); assert.equal(await raw(), saved);
    await page.getByRole('button', { name: '세팅 편집' }).click();
    await page.getByLabel('나의 메모', { exact: true }).fill('저장 실패 후 재시도');
    await page.evaluate(() => { window.originalSetItem = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw Error('Quota test'); }; });
    await save(); assert.equal(await page.locator('#editor').count(), 1); assert.equal(await raw(), saved);
    assert.equal(await page.getByLabel('나의 메모', { exact: true }).inputValue(), '저장 실패 후 재시도');
    await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
    await save(); await page.reload();
    assert.match(await page.locator('#content').innerText(), /저장 실패 후 재시도/);
    const after = await raw();
    for (const kind of ['waystone', 'tablet']) {
      await page.locator(`[data-trade="${kind}"]`).first().click();
      const dialog = page.locator('#trade-dialog'), link = page.locator('#trade-open'); await link.waitFor({ state: 'visible' });
      const url = new URL(await link.getAttribute('href'));
      const query = JSON.parse(gunzipSync(Buffer.from(url.pathname.split('/').at(-1), 'base64url')));
      assert.equal(query.status.option, 'securable'); assert.equal(url.origin, 'https://poe.kakaogames.com');
      await dialog.locator('.dialog-heading').click(); assert.equal(await dialog.isVisible(), true);
      const box = await dialog.boundingBox();
      if (mobile) await page.touchscreen.tap(Math.max(1, box.x / 2), 5); else await page.mouse.click(Math.max(1, box.x / 2), 5);
      assert.equal(await dialog.isVisible(), false); assert.equal(await raw(), after);
    }
    await page.goto(new URL('?method=tablet-drop', root).href);
    await page.getByRole('button', { name: '내 데이터로 복사' }).click();
    await cancel(); assert.equal(await raw(), after);
    await context.close();
  }
  assert.deepEqual(errors, []);
  console.log('PASS: two-column collapsible ranges, ordered controls, three dropdowns in one row, explicit save/cancel, new/copy discard, invalid input and quota rollback/retry, reload, outside popup close, instant-buyout queries, desktop/mobile');
} finally { await browser.close(); }
